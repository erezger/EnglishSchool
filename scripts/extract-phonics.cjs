// Regenerates src/content/phonics.ts from the legacy game: node scripts/extract-phonics.cjs src/legacy/app.js src/content/phonics.ts
const fs = require('fs');
const vm = require('vm');
const [appJs, outFile] = process.argv.slice(2);
const lines = fs.readFileSync(appJs, 'utf8').split('\n');
const start = lines.findIndex((l) => l.startsWith('const LETTER_BANK = {'));
const end = lines.findIndex((l) => l.startsWith('const ALL_WORDS_MAP'));
const code = lines.slice(start, end).join('\n') + '\n;({ LETTER_BANK, LEVELS });';
const { LETTER_BANK, LEVELS } = vm.runInNewContext(code, {});

const letters = Object.entries(LETTER_BANK)
  .filter(([k]) => k.length === 1)
  .map(([key, v]) => ({ key, hebrewName: v.hebrewName, ttsName: v.ttsLetterName, exampleWord: v.exampleWord, exampleHebrew: v.exampleHebrew, exampleEmoji: v.exampleEmoji }));
const sounds = Object.entries(LETTER_BANK).map(([key, v]) => ({ key, upper: v.upper, hebrewSound: v.hebrewSound }));
const levels = LEVELS.map((l) => ({ id: l.id, title: l.title, letters: l.letters || [], isSentenceLevel: !!l.isSentenceLevel }));
const words = [];
const seen = new Set();
for (const lvl of LEVELS) {
  for (const w of lvl.words || []) {
    if (seen.has(w.word)) continue;
    seen.add(w.word);
    words.push({ word: w.word, hebrew: w.hebrew, emoji: w.emoji, level: lvl.id });
  }
}
const sentences = LEVELS.flatMap((l) => (l.sentences || []).map((s) => ({ id: s.id, text: s.text, hebrew: s.hebrew, emoji: s.emoji })));

const out = `/**
 * Phonics content of the original game (letters, decodable words, sentences),
 * shared with server-side features (mastery checks, dictation...).
 * GENERATED by scripts/extract-phonics.cjs from src/legacy/app.js (LETTER_BANK / LEVELS).
 */
export type PhonicsLetter = { key: string; hebrewName: string; ttsName: string; exampleWord: string; exampleHebrew: string; exampleEmoji: string };
export type PhonicsWord = { word: string; hebrew: string; emoji: string; level: number };
export type PhonicsSentence = { id: string; text: string; hebrew: string; emoji: string };
export type PhonicsSound = { key: string; upper: string; hebrewSound: string };
export type PhonicsLevel = { id: number; title: string; letters: string[]; isSentenceLevel: boolean };

export const LETTERS: PhonicsLetter[] = ${JSON.stringify(letters, null, 2)};

export const PHONICS_WORDS: PhonicsWord[] = ${JSON.stringify(words, null, 2)};

export const SENTENCES: PhonicsSentence[] = ${JSON.stringify(sentences, null, 2)};

/** Letters and digraphs (sh, ch...) with the sound hint shown in the game. */
export const SOUNDS: PhonicsSound[] = ${JSON.stringify(sounds, null, 2)};

export const LEVELS: PhonicsLevel[] = ${JSON.stringify(levels, null, 2)};
`;
fs.writeFileSync(outFile, out);
console.log(`letters: ${letters.length}, words: ${words.length}, sentences: ${sentences.length}`);
