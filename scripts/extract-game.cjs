// Generates src/content/game.ts (full letters, levels and shop catalog) from the legacy game:
//   node scripts/extract-game.cjs src/legacy/app.js src/content/game.ts
const fs = require('fs');
const vm = require('vm');
const [appJs, outFile] = process.argv.slice(2);
const lines = fs.readFileSync(appJs, 'utf8').split('\n');
const start = lines.findIndex((l) => l.startsWith('const LETTER_BANK = {'));
const end = lines.findIndex((l) => l.startsWith('/* ====') && lines[lines.indexOf(l) + 1]?.includes('4. LOGGED-IN STUDENT'));
const endIdx = lines.findIndex((l, i) => i > start && l.includes('4. LOGGED-IN STUDENT')) - 1;
const code = lines.slice(start, endIdx).join('\n') + '\n;({ LETTER_BANK, LEVELS, SHOP_AVATARS, SHOP_PETS, SHOP_THEMES });';
const c = vm.runInNewContext(code, {});
void end;

const out = `/**
 * Full content of the original game: letters (name, sound, trick, example, bonus), the 7 levels
 * (words with sound parts, sentences) and the shop catalog.
 * GENERATED by scripts/extract-game.cjs from src/legacy/app.js. Once the legacy game is removed,
 * this file becomes the source of truth and is edited by hand.
 */
export type LetterInfo = {
  upper: string;
  lower: string;
  hebrewName: string;
  ttsLetterName: string;
  hebrewSound: string;
  trick: string;
  phoneme: string;
  exampleWord: string;
  exampleEmoji: string;
  exampleHebrew: string;
  bonus?: { title: string; desc: string; word: string; emoji: string; hebrew: string };
};
export type LevelWord = { word: string; parts: string[]; hebrew: string; emoji: string };
export type LevelSentence = { id: string; text: string; hebrew: string; emoji: string };
export type Level = {
  id: number;
  shortName: string;
  title: string;
  letters: string[];
  words: LevelWord[];
  isSentenceLevel?: boolean;
  sentences?: LevelSentence[];
};
export type ShopItem = { id: string; emoji: string; name: string; cost: number };
export type ShopTheme = { id: string; name: string; icon: string; cost: number; preview: string };

export const LETTER_BANK: Record<string, LetterInfo> = ${JSON.stringify(c.LETTER_BANK, null, 2)};

export const LEVELS: Level[] = ${JSON.stringify(c.LEVELS, null, 2)};

export const SHOP_AVATARS: ShopItem[] = ${JSON.stringify(c.SHOP_AVATARS, null, 2)};

export const SHOP_PETS: ShopItem[] = ${JSON.stringify(c.SHOP_PETS, null, 2)};

export const SHOP_THEMES: ShopTheme[] = ${JSON.stringify(c.SHOP_THEMES, null, 2)};

export const ALL_WORDS: Record<string, LevelWord> = Object.fromEntries(LEVELS.flatMap((l) => l.words.map((w) => [w.word, w])));
`;
fs.writeFileSync(outFile, out);
console.log(`letters: ${Object.keys(c.LETTER_BANK).length}, levels: ${c.LEVELS.length}, avatars: ${c.SHOP_AVATARS.length}, pets: ${c.SHOP_PETS.length}, themes: ${c.SHOP_THEMES.length}`);
